                                <b>¿Qué significa?</b>
                                <p class="card-text">Se suman los resultados obtenidos mes a mes hasta llegar al último periodo evaluado.</p>

                                <b>Ejemplo</b>
                                <p class="card-text">Si en enero tu equipo logró 10, en febrero 20 y en marzo 30, el resultado acumulado será 60.</p>

                                <b>¿Cuándo se usa?</b>
                                <p class="card-text">Es ideal para metas que requieren un crecimiento constante, como ventas anuales o número de clientes atendidos.</p>
