                                <h5 class="text-primary">No Acumulativo</h5>
                            </div>
                            <div class="card-body">
                                <b>¿Qué significa?</b>
                                <p class="card-text">Se mide el promedio de los resultados por cada periodo de tiempo, evaluándolos de forma independiente.</p>

                                <b>Ejemplo</b>
                                <p class="card-text">Si en enero alcanzaste un 90%, en febrero un 95% y en marzo un 85%, el resultado promedio será 90%.</p>

                                <b>¿Cuándo se usa?</b>
                                <p class="card-text">Es útil para indicadores que buscan estabilidad o desempeño constante, como niveles de satisfacción del cliente o puntualidad.</p>
